import { randomBytes } from 'node:crypto';
import { lstat, readFile, readdir, rmdir, stat, unlink, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const OUTPUT = fileURLToPath(new URL('../../wasm-page/dist/ppsspp-web/', import.meta.url));
const SHA256 = /^[a-f0-9]{64}$/i;
const json = value => JSON.stringify(value, null, 2) + '\n';
const error = message => { throw new Error(message); };

export function httpsOrigin(value) {
  let url;
  try { url = new URL(value); } catch { error('部署来源配置无效'); }
  if (typeof value !== 'string' || url.protocol !== 'https:' || url.origin !== value || url.username || url.password || /[\s\\]/.test(value)) error('部署来源必须为精确的 HTTPS origin');
  return url.origin;
}

export function edgeoneConfig() {
  const headers = {
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Embedder-Policy': 'require-corp',
    'Cross-Origin-Resource-Policy': 'same-origin',
    'Content-Security-Policy': "connect-src 'self' blob: https:; worker-src 'self' blob:; form-action 'none'; frame-src 'none'; object-src 'none'; base-uri 'self'",
    'Cache-Control': 'no-cache',
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'no-referrer',
    'X-Frame-Options': 'DENY',
  };
  if (Object.values(headers).some(value => value.length > 1000 || /[^\x20-\x7e]/.test(value))) error('响应头超出静态宿主限制');
  return { headers: [
    { source: '/*', headers: Object.entries(headers).map(([key, value]) => ({ key, value })) },
    { source: '/build-wasm/*.wasm', headers: [{ key: 'Content-Type', value: 'application/wasm' }] },
  ] };
}

async function stampDeployment(output) {
  const path = join(output, 'build-info.json');
  const build = JSON.parse(await readFile(path, 'utf8'));
  if (!SHA256.test(build.revision || '')) error('模拟器构建标识无效');
  // The core hash can stay unchanged when only the web page changes.
  await writeFile(path, json({ ...build, deploymentRevision: randomBytes(32).toString('hex') }));
}

async function clearLegacyCatalog(output) {
  const optionalStat = path => lstat(path).catch(cause => {
    if (cause.code === 'ENOENT') return null;
    throw cause;
  });
  const catalogPath = join(output, 'game-catalog.json');
  const catalog = await optionalStat(catalogPath);
  const manifestDirectory = join(output, 'game-manifests');
  const directory = await optionalStat(manifestDirectory);
  if (catalog && !catalog.isFile()) error('遗留游戏目录必须为普通文件');
  if (directory && !directory.isDirectory()) error('遗留清单目录必须为普通目录');
  const old = directory ? await readdir(manifestDirectory, { withFileTypes: true }) : [];
  if (old.some(entry => !entry.isFile() || !entry.name.endsWith('.json'))) error('遗留清单目录包含非生成文件');
  // These paths were generated by the former deployment configuration step.
  for (const entry of old) await unlink(join(manifestDirectory, entry.name));
  if (directory) await rmdir(manifestDirectory);
  if (catalog) await unlink(catalogPath);
}

export async function prepareDeployment({ output = OUTPUT } = {}) {
  const root = await lstat(output);
  if (!root.isDirectory() || root.isSymbolicLink()) error('静态输出必须为普通目录');
  await clearLegacyCatalog(output);
  await writeFile(join(output, 'edgeone.json'), json(edgeoneConfig()));
  await stampDeployment(output);
  await verifyStaticOutput(output);
}

export async function verifyStaticOutput(output = OUTPUT) {
  for (const name of ['index.html', 'download-worker.js', 'game-download.js', 'online-games.js', 'browser-files.js', 'browser-storage.js', 'ppsspp-runtime.js', 'build-info.json', 'build-wasm/PPSSPPSDL.js', 'build-wasm/PPSSPPSDL.wasm', 'build-wasm/PPSSPPSDL.data']) {
    if (!(await stat(join(output, name))).isFile()) error('静态产物不完整');
  }
  const build = JSON.parse(await readFile(join(output, 'build-info.json'), 'utf8'));
  if (!SHA256.test(build.revision || '') || !SHA256.test(build.deploymentRevision || '')) error('构建或部署标识无效');
  if (JSON.stringify(JSON.parse(await readFile(join(output, 'edgeone.json'), 'utf8'))) !== JSON.stringify(edgeoneConfig())) error('静态宿主响应头配置不一致');
  const visit = async path => {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      if (entry.isSymbolicLink() || /\.(?:iso|cso|chd|pbp|zip|7z|rar)$/i.test(entry.name)
          || ['resources', 'node_modules', '.git', '.env', 'game-catalog.json', 'game-manifests'].includes(entry.name)) error('部署产物包含本地输入或预设下载目录');
      if (entry.isDirectory()) await visit(join(path, entry.name));
    }
  };
  await visit(output);
}

async function main() {
  await prepareDeployment();
  console.log('静态产物、部署标识与宿主响应头配置验证通过。');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(() => { console.error('部署准备失败：请检查完整构建产物与静态宿主配置。'); process.exitCode = 1; });
}
